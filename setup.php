<?php declare(strict_types=1);

// Recreates the tables in a database from config.php: php setup.php [name [username password]]
// The first database by default. Needs an account with CREATE and DROP, which the web account should not have.

if (PHP_SAPI != "cli") {
	exit("Run from the command line.\n");
}
require __DIR__ . "/vendor/autoload.php";
$config = require __DIR__ . "/config.php";
[$dsn, $username, $password] = $config["dbs"][$argv[1] ?? array_key_first($config["dbs"])];
$connection = new PDO($dsn, $argv[2] ?? $username, $argv[3] ?? $password, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$driver = $connection->getAttribute(PDO::ATTR_DRIVER_NAME);
$identities = ["author", "tag", "application", "category"]; // the tables with an identity column and explicit ids in data.sql

foreach (["sql/$driver.sql", "sql/data.sql"] as $file) {
	foreach (preg_split('~;\r?\n~', file_get_contents(__DIR__ . "/$file"), flags: PREG_SPLIT_NO_EMPTY) as $query) {
		$query = trim(preg_replace('~^--.*\n?~m', '', $query));
		if ($query == "") {
			continue;
		}
		preg_match('~^INSERT INTO (\w+) (\([^)]*\)) VALUES~', $query, $insert);
		if ($driver == "oci" && $insert) { // Oracle 21 doesn't support more rows in VALUES
			preg_match_all("~\\((?:'(?:[^']|'')*'|[^'()])*\\)~", substr($query, strlen($insert[0])), $rows);
			foreach ($rows[0] as $row) {
				$connection->exec("INSERT INTO $insert[1] $insert[2] VALUES $row");
			}
		} elseif ($driver == "sqlsrv" && $insert && in_array($insert[1], $identities)) {
			$connection->exec("SET IDENTITY_INSERT $insert[1] ON"); // explicit values of an IDENTITY column
			$connection->exec($query);
			$connection->exec("SET IDENTITY_INSERT $insert[1] OFF");
		} else {
			try {
				$connection->exec($query);
			} catch (PDOException $exception) {
				if (!($driver == "oci" && str_starts_with($query, "DROP") && str_contains($exception->getMessage(), "ORA-00942"))) { // Oracle 21 has no DROP TABLE IF EXISTS
					throw $exception;
				}
			}
		}
	}
}

// the explicit ids in data.sql don't move the identities
foreach ($identities as $table) {
	if ($driver == "pgsql") {
		$connection->query("SELECT setval(pg_get_serial_sequence('$table', 'id'), MAX(id)) FROM $table");
	} elseif ($driver == "oci") {
		$connection->exec("ALTER TABLE $table MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)");
	}
}
echo "Created the tables from sql/$driver.sql and the rows from sql/data.sql.\n";
