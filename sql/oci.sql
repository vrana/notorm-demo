-- The tables of NotORM's tests/software.sql for Oracle, the rows are in data.sql.
-- The ids are identity columns so that the demo can insert rows, setup.php moves them past the inserted ids.
-- Oracle 21 has no DROP TABLE IF EXISTS, setup.php ignores the error of a missing table.

DROP TABLE application_tag CASCADE CONSTRAINTS;

DROP TABLE application CASCADE CONSTRAINTS;

DROP TABLE tag CASCADE CONSTRAINTS;

DROP TABLE author CASCADE CONSTRAINTS;

DROP TABLE category CASCADE CONSTRAINTS;

DROP TABLE setting CASCADE CONSTRAINTS;

DROP TABLE notorm CASCADE CONSTRAINTS;

CREATE TABLE author (
  id number GENERATED BY DEFAULT AS IDENTITY,
  name varchar2(30) NOT NULL,
  web varchar2(100) NOT NULL,
  born date DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE INDEX author_name ON author (name);

CREATE TABLE tag (
  id number GENERATED BY DEFAULT AS IDENTITY,
  name varchar2(20) NOT NULL,
  PRIMARY KEY (id)
);

CREATE INDEX tag_name ON tag (name);

CREATE TABLE application (
  id number GENERATED BY DEFAULT AS IDENTITY,
  author_id number NOT NULL,
  maintainer_id number,
  title varchar2(50) NOT NULL,
  web varchar2(100),
  slogan varchar2(100) NOT NULL,
  logo blob,
  PRIMARY KEY (id),
  CONSTRAINT application_author FOREIGN KEY (author_id) REFERENCES author (id),
  CONSTRAINT application_maintainer FOREIGN KEY (maintainer_id) REFERENCES author (id)
);

CREATE INDEX application_title ON application (title);

CREATE TABLE application_tag (
  application_id number NOT NULL,
  tag_id number NOT NULL,
  PRIMARY KEY (application_id, tag_id),
  CONSTRAINT application_tag_tag FOREIGN KEY (tag_id) REFERENCES tag (id),
  CONSTRAINT application_tag_application FOREIGN KEY (application_id) REFERENCES application (id) ON DELETE CASCADE
);

CREATE TABLE category (
  id number GENERATED BY DEFAULT AS IDENTITY,
  name varchar2(30) NOT NULL,
  parent_id number,
  PRIMARY KEY (id),
  CONSTRAINT category_parent FOREIGN KEY (parent_id) REFERENCES category (id)
);

CREATE INDEX category_name ON category (name);

CREATE TABLE setting (
  site_name varchar2(50) NOT NULL,
  per_page number NOT NULL
);

CREATE TABLE notorm (
  id varchar2(255) NOT NULL,
  data varchar2(4000) NOT NULL,
  PRIMARY KEY (id)
);
