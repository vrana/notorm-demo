<?php declare(strict_types=1);

// Builds www/static/jush/ from vrana/jush; run by Composer after install and update.
// JUSH's own compile.php bundles all modules, this takes only the languages the demo highlights.

$source = __DIR__ . "/vendor/vrana/jush";
$target = __DIR__ . "/www/static/jush";
$modules = ["jush", "jush-php", "jush-sql", "jush-sqlite", "jush-pgsql", "jush-mssql", "jush-oracle"]; // the others use states of jush-sql and jush-sqlite

if (!is_dir($target)) {
	mkdir($target, 0777, true);
}
$js = "// @generated by build-jush.php from vrana/jush\n";
foreach ($modules as $module) {
	$js .= file_get_contents("$source/modules/$module.js") . "\n\n";
}
file_put_contents("$target/jush.js", $js);
copy("$source/jush.css", "$target/jush.css");
copy("$source/jush-dark.css", "$target/jush-dark.css");
echo "Built www/static/jush/ from " . implode(", ", $modules) . "\n";
